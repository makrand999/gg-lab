'use strict';
const assert=require('node:assert/strict');
const {snap,review,layerOf}=require('../public/major2/drawing-assist.js');
const point={id:'a',type:'POINT',x:0,y:20,caption:"a'",viewRole:'ELEVATION'};
const edge={id:'ab',type:'SEGMENT',x:0,y:20,x2:40,y2:20,bisCode:'A',viewRole:'ELEVATION'};
assert.equal(snap({x:.1,y:20},[point,edge],null,1).id,'a');
assert.equal(snap({x:20.2,y:20.1},[edge],null,1).label,'Midpoint');
assert.equal(snap({x:12,y:20.1},[edge],{x:12,y:35},1).label,'Perpendicular');
assert.notEqual(snap({x:50,y:20.1},[edge],{x:50,y:35},1)?.label,'Perpendicular','Perpendicular foot outside a segment is not snapped');
assert.equal(snap({x:.2,y:-30},[point],null,1).x,0,'Corresponding views align at the same X');
assert.equal(snap({x:50,y:80},[point],null,1),null);
assert.equal(layerOf({...edge,bisCode:'G'}),'construction');
assert.equal(layerOf({...edge,type:'DIMENSION'}),'dimensions');
assert.equal(layerOf({...point,type:'TEXT'}),'notes');
assert.match(review([])[0].text,/empty/);
assert.ok(review([{...point,caption:''}]).some(issue=>issue.id==='a'));
assert.ok(review([point]).some(issue=>/one principal view/.test(issue.text)));
assert.equal(review([point,{...point,id:'b',y:-20,caption:'a',viewRole:'PLAN'}]).length,0);
assert.ok(review([point,edge,{...point,id:'b',x:40}]).some(issue=>issue.id==='ab'&&/open endpoint/.test(issue.text)));
console.log('PASS snapping geometry, layer categories and non-grading review suggestions');
